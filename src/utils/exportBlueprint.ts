import type { BlueprintData } from '../types/index';

/**
 * Formats a BlueprintData object into a clean, human-readable plain text document.
 */
export function formatBlueprintAsText(blueprint: BlueprintData): string {
  const { title, emotionalDNA, visualDNA, storyDNA, soundDNA, artPrompt, _meta } = blueprint;

  const colorsText = visualDNA?.colors?.map((c, i) => 
    `  ${i + 1}. [${c.hex}] ${c.name}\n     Meaning: ${c.meaning}`
  ).join('\n\n') || '  (No colors generated)';

  const instrumentsText = soundDNA?.instruments?.join(', ') || 'None specified';
  const soundEffectsText = soundDNA?.soundEffects?.join(', ') || 'None specified';
  const secondaryEmotionsText = emotionalDNA?.secondaryEmotions?.join(', ') || 'None';

  return `================================================================================
                         MOODORA AI CREATIVE BLUEPRINT
================================================================================

TITLE: ${title || 'Untitled Universe'}
SOURCE: ${_meta?.source === 'gemini' ? 'Google Gemini API (gemini-2.5-flash)' : 'MOODORA Verified Fallback Intelligence'}
DATE: ${_meta?.timestamp || new Date().toISOString()}

--------------------------------------------------------------------------------
1. EMOTIONAL DNA
--------------------------------------------------------------------------------
Primary Emotion:     ${emotionalDNA?.primaryEmotion || 'Aligned'}
Secondary Emotions:  ${secondaryEmotionsText}
Affective Intensity: ${emotionalDNA?.intensity || 7} / 10

Interpretation:
${emotionalDNA?.interpretation || 'A deep harmonic synthesis of human sentiment.'}

--------------------------------------------------------------------------------
2. VISUAL DNA (5-COLOR PALETTE & DIRECTION)
--------------------------------------------------------------------------------
Color Palette:
${colorsText}

Visual Style:        ${visualDNA?.style || 'Cinematic'}
Lighting Direction:  ${visualDNA?.lighting || 'Volumetric Ambient'}
Composition:         ${visualDNA?.composition || 'Golden Ratio Horizon'}
Atmosphere:          ${visualDNA?.atmosphere || 'Deep Resonance'}

--------------------------------------------------------------------------------
3. STORY DNA
--------------------------------------------------------------------------------
Story Title: ${storyDNA?.title || title || 'The Resonance of Consciousness'}

Narrative:
${storyDNA?.narrative || 'The stillness of the universe unfolded without words.'}

Central Philosophical Message:
"${storyDNA?.message || 'Within every storm lies an unbroken center of quiet.'}"

--------------------------------------------------------------------------------
4. SOUND DNA (ACOUSTIC DIRECTION)
--------------------------------------------------------------------------------
Recommended Genre:   ${soundDNA?.genre || 'Ambient Psychoacoustic'}
Sound Mood:          ${soundDNA?.mood || 'Expansive & Serene'}
Tempo & Cadence:     ${soundDNA?.tempo || '60 BPM'}
Instruments:         ${instrumentsText}
Sound Effects & Sfx: ${soundEffectsText}

Note: Compositional and acoustic direction for sound designers and music generators.

--------------------------------------------------------------------------------
5. COMPLETE IMAGE-GENERATION PROMPT
--------------------------------------------------------------------------------
${artPrompt || 'A cinematic masterpiece reflecting emotional depth, 8k resolution.'}

================================================================================
              Generated by MOODORA AI — Feel it. Transform it. Create it.
================================================================================
`;
}

/**
 * Generates and triggers download of a .txt file containing the complete creative blueprint.
 */
export function downloadBlueprintTxt(blueprint: BlueprintData, customFilename?: string): void {
  const content = formatBlueprintAsText(blueprint);
  const blob = new Blob([content], { type: 'text/plain;charset=utf-8' });
  
  const cleanTitle = (blueprint.title || 'moodora-creation')
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/(^-|-$)/g, '');
    
  const filename = customFilename || `moodora-${cleanTitle}-${Date.now()}.txt`;
  
  const url = URL.createObjectURL(blob);
  const link = document.createElement('a');
  link.href = url;
  link.download = filename;
  document.body.appendChild(link);
  link.click();
  document.body.removeChild(link);
  URL.revokeObjectURL(url);
}
